-- ArenaGeo: estrutura inicial para cadastro.
-- Decisão atual: autenticação e regras de negócio permanecem no backend Spring Boot.
-- A coluna usuarios.senha_hash deve receber somente hash BCrypt/Argon2, nunca senha em texto puro.
-- RLS é habilitado sem políticas para impedir acesso direto pelo client Supabase até definirmos as políticas.
-- Esta migration não apaga nem altera tabelas existentes; conflito com uma tabela homônima deve ser revisado.

begin;

create table public.tipos_conta (
    id smallint generated by default as identity primary key,
    codigo varchar(30) not null unique,
    nome varchar(80) not null,
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    constraint ck_tipos_conta_codigo_maiusculo
        check (codigo = upper(codigo))
);

insert into public.tipos_conta (codigo, nome)
values
    ('PLAYER', 'Jogador'),
    ('BUSINESS', 'Empresa');

create table public.usuarios (
    id bigint generated by default as identity primary key,
    email varchar(254) not null,
    senha_hash text not null,
    tipo_conta_id smallint not null references public.tipos_conta(id),
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create unique index uq_usuarios_email_normalizado
    on public.usuarios (lower(btrim(email)));

create table public.pessoas (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null unique
        references public.usuarios(id) on delete cascade,
    nome_completo varchar(160) not null,
    nome_usuario varchar(30),
    cpf varchar(11),
    telefone varchar(20),
    data_nascimento date,
    foto_perfil_url text,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now(),
    constraint ck_pessoas_cpf
        check (cpf is null or cpf ~ '^[0-9]{11}$'),
    constraint ck_pessoas_nome_usuario
        check (nome_usuario is null or length(btrim(nome_usuario)) between 3 and 30)
);

create unique index uq_pessoas_nome_usuario_normalizado
    on public.pessoas (lower(btrim(nome_usuario)))
    where nome_usuario is not null;

create unique index uq_pessoas_cpf
    on public.pessoas (cpf)
    where cpf is not null;

create table public.enderecos (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null
        references public.usuarios(id) on delete cascade,
    tipo_endereco varchar(20) not null default 'PRINCIPAL',
    cep varchar(8),
    uf char(2),
    cidade varchar(120) not null,
    bairro varchar(120),
    logradouro varchar(160),
    numero varchar(20),
    complemento varchar(120),
    latitude numeric(9, 6),
    longitude numeric(9, 6),
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now(),
    constraint ck_enderecos_tipo
        check (tipo_endereco in ('PRINCIPAL', 'RESIDENCIAL', 'COMERCIAL', 'ARENA')),
    constraint ck_enderecos_cep
        check (cep is null or cep ~ '^[0-9]{8}$'),
    constraint ck_enderecos_uf
        check (uf is null or uf ~ '^[A-Z]{2}$'),
    constraint ck_enderecos_coordenadas_preenchidas_juntas
        check ((latitude is null and longitude is null)
            or (latitude is not null and longitude is not null)),
    constraint ck_enderecos_latitude
        check (latitude is null or latitude between -90 and 90),
    constraint ck_enderecos_longitude
        check (longitude is null or longitude between -180 and 180)
);

create index idx_enderecos_usuario_id
    on public.enderecos (usuario_id);

create table public.jogadores (
    id bigint generated by default as identity primary key,
    pessoa_id bigint not null unique
        references public.pessoas(id) on delete cascade,
    endereco_id bigint not null
        references public.enderecos(id),
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create index idx_jogadores_endereco_id
    on public.jogadores (endereco_id);

create table public.empresas (
    id bigint generated by default as identity primary key,
    pessoa_responsavel_id bigint not null unique
        references public.pessoas(id) on delete cascade,
    endereco_id bigint not null
        references public.enderecos(id),
    razao_social varchar(180) not null,
    nome_fantasia varchar(180) not null,
    cnpj varchar(14) not null unique,
    inscricao_estadual varchar(30),
    telefone_comercial varchar(20) not null,
    email_comercial varchar(254) not null,
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now(),
    constraint ck_empresas_cnpj
        check (cnpj ~ '^[0-9]{14}$')
);

create index idx_empresas_endereco_id
    on public.empresas (endereco_id);

create table public.arenas (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null
        references public.empresas(id) on delete cascade,
    endereco_id bigint not null
        references public.enderecos(id),
    nome varchar(160) not null,
    descricao text not null default '',
    imagem_url text,
    telefone varchar(20) not null,
    email varchar(254) not null,
    website text,
    instagram varchar(120),
    horario_funcionamento text not null,
    ativo boolean not null default true,
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
);

create index idx_arenas_empresa_id
    on public.arenas (empresa_id);

create index idx_arenas_endereco_id
    on public.arenas (endereco_id);

create table public.esportes (
    id bigint generated by default as identity primary key,
    nome varchar(80) not null unique,
    slug varchar(100) not null unique,
    ativo boolean not null default true,
    criado_em timestamptz not null default now()
);

insert into public.esportes (nome, slug)
values
    ('Futebol', 'futebol'),
    ('Futsal', 'futsal'),
    ('Beach Tennis', 'beach-tennis'),
    ('Tênis', 'tenis'),
    ('Vôlei', 'volei');

create table public.niveis_habilidade (
    id bigint generated by default as identity primary key,
    nome varchar(80) not null unique,
    descricao text not null default '',
    ativo boolean not null default true,
    criado_em timestamptz not null default now()
);

create table public.jogador_esportes (
    jogador_id bigint not null
        references public.jogadores(id) on delete cascade,
    esporte_id bigint not null
        references public.esportes(id),
    nivel_habilidade_id bigint not null
        references public.niveis_habilidade(id),
    criado_em timestamptz not null default now(),
    constraint pk_jogador_esportes primary key (jogador_id, esporte_id)
);

create index idx_jogador_esportes_esporte_id
    on public.jogador_esportes (esporte_id);

create or replace function public.definir_atualizado_em()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
    new.atualizado_em := now();
    return new;
end;
$$;

create trigger trg_usuarios_atualizado_em
before update on public.usuarios
for each row execute function public.definir_atualizado_em();

create trigger trg_pessoas_atualizado_em
before update on public.pessoas
for each row execute function public.definir_atualizado_em();

create trigger trg_enderecos_atualizado_em
before update on public.enderecos
for each row execute function public.definir_atualizado_em();

create trigger trg_jogadores_atualizado_em
before update on public.jogadores
for each row execute function public.definir_atualizado_em();

create trigger trg_empresas_atualizado_em
before update on public.empresas
for each row execute function public.definir_atualizado_em();

create trigger trg_arenas_atualizado_em
before update on public.arenas
for each row execute function public.definir_atualizado_em();

-- As tabelas não ficam acessíveis diretamente pelo client Supabase sem políticas.
-- O acesso público ao catálogo e às arenas deve ser exposto pelo backend Java
-- com DTOs que selecionem somente os campos apropriados.
alter table public.tipos_conta enable row level security;
alter table public.usuarios enable row level security;
alter table public.pessoas enable row level security;
alter table public.enderecos enable row level security;
alter table public.jogadores enable row level security;
alter table public.empresas enable row level security;
alter table public.arenas enable row level security;
alter table public.esportes enable row level security;
alter table public.niveis_habilidade enable row level security;
alter table public.jogador_esportes enable row level security;

comment on table public.usuarios is
    'Conta de acesso; senha_hash deve conter somente hash criado pelo backend.';
comment on table public.pessoas is
    'Dados pessoais do jogador ou responsável por uma conta comercial.';
comment on table public.enderecos is
    'Endereço vinculado ao usuário; o cadastro de arena pode compartilhar este endereço.';
comment on table public.jogador_esportes is
    'Relacionamento entre jogador, esporte e nível de habilidade.';

commit;
